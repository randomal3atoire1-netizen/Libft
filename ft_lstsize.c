#include "libft.h"

unsigned int	ft_lstsize(t_list *lst)
{
	unsigned int	len;

	len = 1;
	if (!lst)
		return (0);
	while (lst->next)
	{
		len++;
		lst = lst->next;
	}
	return (len);
}
