char	*ft_strrchr(const char *s, int c)
{
	int		i;

	i = 0;
	while (s && s[i])
		i++;
	while (s && i > 0 && s[i] != c)
		i--;
	if (s && s[i] == c)
		return (&((char *)s)[i]);
	return (0);
}
